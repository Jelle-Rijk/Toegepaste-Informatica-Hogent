import WeatherRepository from "./WeatherRepository.js";

export default class WeatherComponent {
  #weatherRepository;
  #cities = ["Gent", "Amsterdam", "London"];

  constructor() {
    this.#weatherRepository = new WeatherRepository();
    this.#initialiseHTML();
  }

  #initialiseHTML() {
    // TODO
    let url = "data-json/weather";
    this.#cities.forEach((c) => {
      url += c;
    });
    console.log(url);
    this.#fetchData(url + ".json");
    this.#citiesToHTML(this.#cities);
    this.#showWeather(this.#cities[0]);
  }

  async #fetchData(url) {
    // TODO
    try {
      const data = await fetch(url);
      //   const jsonData = await data.json();
      //   const jsonData = await JSON.parse(data);
      const jsonData =console.log(data.json());
      this.#weatherRepository.addWeatherData(data);
    } catch (err) {
      alert(err);
    }
  }

  #citiesToHTML(cities) {
    // TODO
    const container = document.getElementById("cities");
    for (const city of cities) {
      const li = document.createElement("li");
      li.className = "nav-item";
      const anchor = document.createElement("a");
      anchor.className = "nav-link";
      anchor.href = "#";
      anchor.innerText = city;

      li.appendChild(anchor);
      li.addEventListener("click", () => {
        const navlinks = document.getElementsByClassName("nav-link");
        navlinks.forEach((l) => l.classList.remove("active"));
        li.classList.add("active");
      });
      container.appendChild(li);
    }
  }

  #showWeather(cityName) {
    // TODO show current weather
    const info = document.getElementById("weather-info");
    const weather = this.#weatherRepository.getCurrentWeather(cityName);
    info.innerHTML = "";
    info.insertAdjacentHTML(
      "beforeend",
      `<p class="fs-1 text-center">{weather.temperature}</p>
        <p><img width="200" height="200" src="${weather.icon}" alt="${weather.description}"></p>`,
    );
    //TODO show statistics

    const stats = document.getElementById("statistics");
    stats.innerHTML = "";
    const statsData = this.#weatherRepository(cityName);
    stats.insertAdjacentHTML(
      "beforeend",
      `<h3>Statistics next 8 days</h3>
        <p>Minimum temperature: ${statsData.minTemp}°C</p>
        <p>Maximum temperature: ${statsData.maxTemp}°C</p>
        <p>Average humidity: ${statsData.averageHumidity}%</p>`,
    );
  }
}

